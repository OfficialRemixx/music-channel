"""Section 5.2 default provider: two-phase Kaggle + ACE-Step 1.5.

Phase A1 (submit): render a per-batch Kaggle kernel (kernel.py + kernel-metadata.json)
and `kaggle kernels push` it, then return immediately -- never hold a GitHub Actions
runner waiting on a GPU job.

Phase A2 (poll / fetch): a separate, cheap, frequent workflow calls `poll()`
(`kaggle kernels status`) and only calls `fetch()` (`kaggle kernels output`) once the
kernel reports complete.

ACE-Step: open-source text-to-music diffusion model (https://github.com/ace-step/ACE-Step,
Apache 2.0). Pinned to a specific commit so every generated track can cite an exact,
reproducible model version in its manifest (R-series provenance requirement).
"""
from __future__ import annotations

import json
import os
import re
import subprocess
import tempfile
from pathlib import Path

from common.logging_setup import get_logger

from .base import BatchSpec, Job, MusicProvider

log = get_logger(__name__)

# Pinned per the project's own rule 0.2 (never float on an upstream commit) --
# verified directly against the real ACE-Step source (infer.py / infer-api.py /
# acestep/data_sampler.py / examples/default/input_params) rather than guessed.
ACE_STEP_COMMIT = "1bee4c9f5b43e30995f8d4d33b3919197ce1bd68"
ACE_STEP_REPO = "https://github.com/ace-step/ACE-Step.git"
ACE_STEP_LICENSE = "Apache-2.0"
ACE_STEP_MODEL_NAME = "ACE-Step-v1-3.5B"

KERNEL_SLUG_PREFIX = "mc-gen"
DEFAULT_TRACK_DURATION_S = 90

# Confirmed real default generation parameters, taken from ACE-Step's own
# examples/default/input_params/*.json sample. We only override the lyrics-related
# fields (instrumental-only niche) and audio_duration/prompt/seed per track.
ACE_STEP_DEFAULTS = {
    "infer_step": 60,
    "guidance_scale": 15,
    "scheduler_type": "euler",
    "cfg_type": "apg",
    "omega_scale": 10,
    "guidance_interval": 0.5,
    "guidance_interval_decay": 0.0,
    "min_guidance_scale": 3,
    "use_erg_tag": True,
    "use_erg_lyric": False,
    "use_erg_diffusion": True,
    "oss_steps": [],
    "guidance_scale_text": 0.0,
    "guidance_scale_lyric": 0.0,
}

KERNEL_SCRIPT_TEMPLATE = '''\
"""Auto-generated by generate/kaggle_acestep.py -- do not hand-edit.
Installs ACE-Step at a pinned commit, generates one track per prompt with
ACEStepPipeline, and writes a manifest.json alongside the .wav files so the
A2 collect step can build [{{path, prompt, seed, model, commit, license}}]."""
import json
import random
import subprocess
import sys

COMMIT = {commit!r}
REPO = {repo!r}
MODEL_NAME = {model_name!r}
LICENSE = {license!r}
PROMPTS = {prompts_json}
DEFAULTS = {defaults_json}

subprocess.run(
    [sys.executable, "-m", "pip", "install", "-q", f"git+{{REPO}}@{{COMMIT}}"],
    check=True,
)

from acestep.pipeline_ace_step import ACEStepPipeline  # noqa: E402

pipeline = ACEStepPipeline(checkpoint_dir="", dtype="bfloat16")

manifest = []
for i, item in enumerate(PROMPTS):
    seed = random.randint(1, 2**31 - 1)
    out_name = f"track_{{i:03d}}.wav"
    out_path = f"/kaggle/working/{{out_name}}"
    pipeline(
        audio_duration=item.get("duration", {default_duration}),
        prompt=item["prompt"],
        lyrics="[instrumental]",
        manual_seeds=str(seed),
        save_path=out_path,
        **DEFAULTS,
    )
    manifest.append({{
        "path": out_name,
        "prompt": item["prompt"],
        "seed": seed,
        "model": MODEL_NAME,
        "commit": COMMIT,
        "license": LICENSE,
    }})

with open("/kaggle/working/manifest.json", "w") as f:
    json.dump(manifest, f, indent=2)

print(f"wrote {{len(manifest)}} tracks + manifest.json")
'''


def _slugify(value: str) -> str:
    slug = re.sub(r"[^a-z0-9]+", "-", value.lower()).strip("-")
    return (slug or "batch")[:50]


class KaggleAceStepProvider(MusicProvider):
    name = "kaggle_acestep"

    def __init__(self, cfg: dict):
        self.cfg = cfg
        self.dry_run = cfg.get("dry_run", True)

    def _kaggle_username(self) -> str:
        username = os.environ.get("KAGGLE_USERNAME")
        if not username:
            raise RuntimeError(
                "KAGGLE_USERNAME is not set. Kaggle's kernel id format is "
                "'<username>/<slug>' and the current token-based auth (KAGGLE_API_TOKEN) "
                "does not embed the username, so it must be supplied separately as a "
                "GitHub secret / env var."
            )
        return username

    def submit(self, batch_spec: BatchSpec) -> Job:
        if self.dry_run:
            log.info(
                "kaggle_acestep.submit: dry_run, faking a pending job for %s",
                batch_spec.batch_id,
            )
            return Job(
                job_id=f"dryrun-{batch_spec.batch_id}",
                provider=self.name,
                status="pending",
                meta={"dry_run": True},
            )

        username = self._kaggle_username()
        slug = f"{KERNEL_SLUG_PREFIX}-{_slugify(batch_spec.batch_id)}"
        kernel_id = f"{username}/{slug}"

        kernel_dir = Path(tempfile.mkdtemp(prefix="kaggle-kernel-"))
        script = KERNEL_SCRIPT_TEMPLATE.format(
            commit=ACE_STEP_COMMIT,
            repo=ACE_STEP_REPO,
            model_name=ACE_STEP_MODEL_NAME,
            license=ACE_STEP_LICENSE,
            prompts_json=json.dumps(batch_spec.prompts),
            defaults_json=json.dumps(ACE_STEP_DEFAULTS),
            default_duration=batch_spec.extra.get("duration", DEFAULT_TRACK_DURATION_S),
        )
        (kernel_dir / "kernel.py").write_text(script, encoding="utf-8")

        metadata = {
            "id": kernel_id,
            "title": slug,
            "code_file": "kernel.py",
            "language": "python",
            "kernel_type": "script",
            "is_private": True,
            "enable_gpu": True,
            "enable_internet": True,
            "machine_shape": "NvidiaTeslaT4",
        }
        (kernel_dir / "kernel-metadata.json").write_text(
            json.dumps(metadata, indent=2), encoding="utf-8"
        )

        log.info("kaggle_acestep.submit: pushing kernel %s (%d prompts)",
                  kernel_id, len(batch_spec.prompts))
        result = subprocess.run(
            ["kaggle", "kernels", "push", "-p", str(kernel_dir)],
            check=False,
            capture_output=True,
            text=True,
            timeout=300,
        )
        if result.returncode != 0:
            log.error("kaggle_acestep.submit: push failed: %s", result.stderr.strip())
            raise RuntimeError(f"kaggle kernels push failed: {result.stderr.strip()}")

        return Job(
            job_id=kernel_id,
            provider=self.name,
            status="pending",
            meta={"slug": slug, "batch_id": batch_spec.batch_id},
        )

    def poll(self, job: Job) -> Job:
        if job.meta.get("dry_run"):
            job.status = "complete"
            return job

        result = subprocess.run(
            ["kaggle", "kernels", "status", job.job_id],
            check=False,
            capture_output=True,
            text=True,
            timeout=60,
        )
        if result.returncode != 0:
            log.error("kaggle_acestep.poll: status check failed for %s: %s",
                       job.job_id, result.stderr.strip())
            job.status = "failed"
            return job

        status_text = (result.stdout or "").strip().lower()
        if "complete" in status_text:
            job.status = "complete"
        elif any(bad in status_text for bad in ("error", "fail", "cancel")):
            job.status = "failed"
        else:
            # "running" / "queued" and anything else not yet recognized -- keep
            # polling rather than guessing a terminal state.
            job.status = "running"
        job.meta["last_status_text"] = status_text
        return job

    def fetch(self, job: Job) -> list[dict]:
        if job.meta.get("dry_run"):
            return []

        out_dir = Path(tempfile.mkdtemp(prefix="kaggle-output-"))
        result = subprocess.run(
            ["kaggle", "kernels", "output", job.job_id, "-p", str(out_dir)],
            check=False,
            capture_output=True,
            text=True,
            timeout=600,
        )
        if result.returncode != 0:
            log.error("kaggle_acestep.fetch: output download failed for %s: %s",
                       job.job_id, result.stderr.strip())
            return []

        manifest_path = out_dir / "manifest.json"
        if not manifest_path.exists():
            log.error("kaggle_acestep.fetch: no manifest.json in output for %s", job.job_id)
            return []

        manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
        tracks = []
        for entry in manifest:
            track_path = out_dir / entry["path"]
            if not track_path.exists():
                log.warning("kaggle_acestep.fetch: manifest entry %s missing on disk",
                            entry["path"])
                continue
            tracks.append({**entry, "path": str(track_path)})
        return tracks
